#!/bin/bash
# GitHub publication is deliberately separate from Maven's local packaging lifecycle.
# The workflow serializes this script and grants its job the only write token.
set -euo pipefail
export LC_ALL=C

die() { printf 'MicroCol publication: %s\n' "$*" >&2; exit 1; }
[ "$#" -eq 5 ] && [ "$4" = --repository ] || die 'Usage: publish.sh DIRECTORY BUILD_ID FULL_SHA --repository OWNER/REPO'
DIRECTORY=$(CDPATH= cd -- "$1" && pwd) || die 'Asset directory does not exist.'
BUILD=$2
COMMIT=$3
REPOSITORY=$5
BUILD_PATTERN='^dev-[1-9][0-9]*-[0-9a-f]{12}$'
SHA_PATTERN='^[0-9a-f]{40}$'
HASH_PATTERN='^[0-9a-f]{64}$'
REPOSITORY_PATTERN='^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$'
[[ $REPOSITORY =~ $REPOSITORY_PATTERN ]] || die 'Invalid GitHub repository.'
command -v jq >/dev/null || die 'jq is required.'
command -v gh >/dev/null || die 'GitHub CLI is required.'
if command -v sha256sum >/dev/null; then HASH_COMMAND=(sha256sum); else HASH_COMMAND=(shasum -a 256); fi
WORK=$(mktemp -d "${TMPDIR:-/tmp}/microcol-publication.XXXXXXXX") || die 'Cannot create temporary directory.'
trap 'rm -rf -- "$WORK"' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM HUP

valid_build() {
    [[ $1 =~ $BUILD_PATTERN ]] && [[ $2 =~ $SHA_PATTERN ]] && [ "${1##*-}" = "${2:0:12}" ]
}
valid_build "$BUILD" "$COMMIT" || die 'Invalid build identifier or source revision.'

hash_file() {
    local result
    # Hash stdin so spaces/backslashes in the checkout path cannot change checksum syntax.
    result=$("${HASH_COMMAND[@]}" < "$1") || die "Cannot hash $1"
    result=${result%% *}
    [[ $result =~ $HASH_PATTERN ]] || die 'Invalid checksum tool output.'
    printf '%s\n' "$result"
}

archive_name() {
    local extension=zip
    [ "$1" != linux-x86_64 ] || extension=tar.gz
    printf 'MicroCol-%s-%s.%s\n' "$1" "$2" "$extension"
}

required_names() {
    printf '%s\n' MicroCol-Dev-macos.zip MicroCol-Dev-linux.tar.gz
    local platform extension
    for platform in macos-arm64 macos-x86_64 linux-x86_64; do
        archive_name "$platform" "$BUILD"
        extension=dmg
        [ "$platform" != linux-x86_64 ] || extension=deb
        printf 'MicroCol-%s-%s.%s\n' "$platform" "$BUILD" "$extension"
    done
}
required_names | sort > "$WORK/assets"
{ cat "$WORK/assets"; printf '%s\n' manifest.tsv SHA256SUMS; } | sort > "$WORK/published"

check_files() {
    local directory=$1 expected=$2 path name
    : > "$WORK/actual"
    shopt -s nullglob dotglob
    for path in "$directory"/*; do
        name=${path##*/}
        [ -f "$path" ] && [ ! -L "$path" ] && [ -s "$path" ] || die "Asset is not a nonempty regular file: $name"
        printf '%s\n' "$name" >> "$WORK/actual"
    done
    shopt -u nullglob dotglob
    sort "$WORK/actual" -o "$WORK/actual"
    cmp -s "$WORK/actual" "$expected" || die 'Incomplete or unexpected release asset set.'
}

check_input() {
    local name expected actual sidecar
    cp "$WORK/assets" "$WORK/input-names"
    while IFS= read -r name; do printf '%s.sha256\n' "$name"; done < "$WORK/assets" >> "$WORK/input-names"
    # A local retry may retain these two files generated by a preceding invocation.
    for name in manifest.tsv SHA256SUMS; do
        [ ! -e "$DIRECTORY/$name" ] || printf '%s\n' "$name" >> "$WORK/input-names"
    done
    sort "$WORK/input-names" -o "$WORK/input-names"
    check_files "$DIRECTORY" "$WORK/input-names"
    while IFS= read -r name; do
        sidecar=$DIRECTORY/$name.sha256
        [ "$(wc -c < "$sidecar")" -eq 65 ] || die "Invalid checksum sidecar: $name"
        IFS= read -r expected < "$sidecar" || die "Invalid checksum sidecar: $name"
        [[ $expected =~ $HASH_PATTERN ]] || die "Invalid checksum sidecar: $name"
        actual=$(hash_file "$DIRECTORY/$name")
        [ "$actual" = "$expected" ] || die "Checksum sidecar does not match $name"
    done < "$WORK/assets"
}

make_manifest() {
    local directory=$1 platform name
    printf 'microcol-dev-v1\nbuild\t%s\t%s\n' "$BUILD" "$COMMIT"
    for platform in macos-arm64 macos-x86_64 linux-x86_64; do
        name=$(archive_name "$platform" "$BUILD")
        printf 'asset\t%s\t%s\t%s\n' "$platform" "$name" "$(hash_file "$directory/$name")"
    done
}

make_checksums() {
    local directory=$1 name
    while IFS= read -r name; do
        [ "$name" != SHA256SUMS ] || continue
        printf '%s  %s\n' "$(hash_file "$directory/$name")" "$name"
    done < "$WORK/published"
}

parse_manifest() {
    local path=$1 line number=0 tabs kind a b c extra platform expected
    local arm=0 intel=0 linux=0
    PARSED_BUILD=; PARSED_COMMIT=
    while IFS= read -r line || [ -n "$line" ]; do
        number=$((number + 1))
        case "$line" in *$'\r'*) die 'Invalid manifest line ending.' ;; esac
        if [ "$number" -eq 1 ]; then
            [ "$line" = microcol-dev-v1 ] || die 'Invalid manifest header.'
            continue
        fi
        tabs=${line//[!$'\t']/}
        IFS=$'\t' read -r kind a b c extra <<< "$line"
        if [ "$number" -eq 2 ]; then
            [ "${#tabs}" -eq 2 ] && [ "$kind" = build ] && valid_build "$a" "$b" || die 'Invalid manifest build row.'
            PARSED_BUILD=$a; PARSED_COMMIT=$b
            continue
        fi
        [ "${#tabs}" -eq 3 ] && [ "$kind" = asset ] && [[ $c =~ $HASH_PATTERN ]] || die 'Invalid manifest asset row.'
        case "$a" in
            macos-arm64) [ "$arm" -eq 0 ] || die 'Duplicate platform.'; arm=1 ;;
            macos-x86_64) [ "$intel" -eq 0 ] || die 'Duplicate platform.'; intel=1 ;;
            linux-x86_64) [ "$linux" -eq 0 ] || die 'Duplicate platform.'; linux=1 ;;
            *) die 'Invalid manifest platform.' ;;
        esac
        expected=$(archive_name "$a" "$PARSED_BUILD")
        [ "$b" = "$expected" ] || die 'Unexpected manifest asset filename.'
    done < "$path"
    [ "$number" -eq 5 ] && [ "$arm$intel$linux" = 111 ] || die 'Incomplete manifest.'
}

gh_release() { gh release "$@" --repo "$REPOSITORY"; }

lookup_release() {
    local tag=$1 output=$2 id
    if gh api "repos/$REPOSITORY/releases/tags/$tag" > "$output" 2> "$WORK/api-error"; then return 0; fi
    grep -Fq 'HTTP 404' "$WORK/api-error" || { cat "$WORK/api-error" >&2; die 'Release lookup failed.'; }
    # The REST tag endpoint omits drafts; resolve their numeric database ID first.
    if gh_release view "$tag" --json databaseId > "$WORK/release-id" 2> "$WORK/api-error"; then
        id=$(jq -er '.databaseId | select(type == "number")' "$WORK/release-id") || die 'Invalid draft release ID.'
        gh api "repos/$REPOSITORY/releases/$id" > "$output" || die 'Draft release lookup failed.'
        return 0
    fi
    [ "$(cat "$WORK/api-error")" = 'release not found' ] || { cat "$WORK/api-error" >&2; die 'Draft release lookup failed.'; }
    return 1
}

download_asset() {
    gh_release download "$1" --pattern "$2" --output "$3" --clobber || die "Cannot download release asset $2"
}

verify_uploads() {
    local name expected remote
    lookup_release "$BUILD" "$WORK/release.json" || die 'Uploaded draft release cannot be found.'
    jq -er '.assets[].name' "$WORK/release.json" | sort > "$WORK/remote-names" || die 'Invalid release assets response.'
    cmp -s "$WORK/remote-names" "$WORK/published" || die 'Remote release asset set is incomplete or unexpected.'
    while IFS= read -r name; do
        expected=$(hash_file "$DIRECTORY/$name")
        remote=$(jq -r --arg name "$name" '.assets[] | select(.name == $name) | .digest // ""' "$WORK/release.json") || die 'Invalid release digest response.'
        [ "$remote" != "sha256:$expected" ] || continue
        # Older API responses may omit digests; verify the uploaded bytes instead.
        download_asset "$BUILD" "$name" "$WORK/downloaded"
        [ "$(hash_file "$WORK/downloaded")" = "$expected" ] || die "Remote release checksum mismatch: $name"
    done < "$WORK/published"
}

newer_run() {
    local next=${1#dev-} previous=${2#dev-}
    next=${next%%-*}; previous=${previous%%-*}
    # Compare decimal strings without integer overflow; build IDs forbid leading zeros.
    [ "${#next}" -gt "${#previous}" ] || { [ "${#next}" -eq "${#previous}" ] && [[ $next > $previous ]]; }
}

can_promote() {
    local main
    gh api "repos/$REPOSITORY/git/ref/heads/main" > "$WORK/main.json" || die 'Cannot read current main revision.'
    main=$(jq -er '.object.sha' "$WORK/main.json") || die 'Invalid main revision response.'
    [[ $main =~ $SHA_PATTERN ]] || die 'Invalid main revision.'
    [ "$main" = "$COMMIT" ] || return 1
    if lookup_release dev "$WORK/channel.json"; then
        if jq -e '.assets | any(.name == "manifest.tsv")' "$WORK/channel.json" >/dev/null; then
            download_asset dev manifest.tsv "$WORK/previous-manifest.tsv"
            parse_manifest "$WORK/previous-manifest.tsv"
            newer_run "$BUILD" "$PARSED_BUILD" || return 1
        fi
    fi
    return 0
}

check_input
make_manifest "$DIRECTORY" > "$DIRECTORY/manifest.tsv"
make_checksums "$DIRECTORY" > "$DIRECTORY/SHA256SUMS"
cat > "$WORK/notes.md" <<EOF
Development build \`$BUILD\` from \`$COMMIT\`.

All three native builds and their game unit tests completed successfully. macOS packages are unsigned and are not notarized.

Install the one-time **MicroCol Dev** launcher to receive the latest successful development build when starting the game. Download manual DMG/DEB installers from [this complete build release](https://github.com/$REPOSITORY/releases/tag/$BUILD).

[Installation instructions](https://${REPOSITORY%%/*}.github.io/${REPOSITORY##*/}/development-builds.html)
EOF

EXISTS=0
if lookup_release "$BUILD" "$WORK/release.json"; then EXISTS=1; fi
if [ "$EXISTS" -eq 1 ] && [ "$(jq -er '.draft | tostring' "$WORK/release.json")" = false ]; then
    # Published bytes are immutable by policy, including when a workflow is rerun.
    mkdir "$WORK/original"
    gh_release download "$BUILD" --dir "$WORK/original" || die 'Cannot download the existing immutable release.'
    check_files "$WORK/original" "$WORK/published"
    parse_manifest "$WORK/original/manifest.tsv"
    [ "$PARSED_BUILD" = "$BUILD" ] && [ "$PARSED_COMMIT" = "$COMMIT" ] || die 'Existing build tag belongs to another revision.'
    make_manifest "$WORK/original" > "$WORK/expected-manifest"
    cmp -s "$WORK/expected-manifest" "$WORK/original/manifest.tsv" || die 'Existing release manifest checksums do not match its archives.'
    make_checksums "$WORK/original" > "$WORK/expected-checksums"
    cmp -s "$WORK/expected-checksums" "$WORK/original/SHA256SUMS" || die 'Existing release checksums do not match its assets.'
    DIRECTORY=$WORK/original
else
    if [ "$EXISTS" -eq 0 ]; then
        gh_release create "$BUILD" --target "$COMMIT" --prerelease --draft --title "MicroCol $BUILD" --notes-file "$WORK/notes.md" || die 'Cannot create draft release.'
    fi
    ASSET_PATHS=()
    while IFS= read -r name; do ASSET_PATHS+=("$DIRECTORY/$name"); done < "$WORK/published"
    # Clobber is limited to drafts; a partial upload can safely be retried.
    gh_release upload "$BUILD" "${ASSET_PATHS[@]}" --clobber || die 'Draft asset upload failed.'
    verify_uploads
    gh_release edit "$BUILD" --draft=false --prerelease --latest=false || die 'Cannot publish verified build.'
fi

if ! can_promote; then printf 'Built %s; keeping the newer/current development channel unchanged.\n' "$BUILD"; exit 0; fi
if ! lookup_release dev "$WORK/channel.json"; then
    gh_release create dev --target "$COMMIT" --prerelease --latest=false --title 'MicroCol development channel' --notes-file "$WORK/notes.md" || die 'Cannot create development channel.'
fi
gh_release upload dev "$DIRECTORY/MicroCol-Dev-macos.zip" "$DIRECTORY/MicroCol-Dev-linux.tar.gz" --clobber || die 'Launcher publication failed.'
# Main may advance during uploads. Recheck both source revision and promoted run.
if ! can_promote; then printf 'Main advanced during publication; leaving the development manifest unchanged.\n'; exit 0; fi
gh_release upload dev "$DIRECTORY/manifest.tsv" --clobber || die 'Development manifest publication failed.'
gh_release edit dev --title 'MicroCol development channel' --notes-file "$WORK/notes.md" --prerelease --latest=false || die 'Cannot update development release notes.'
printf 'Promoted development channel to %s\n' "$BUILD"
if [ -n "${GITHUB_STEP_SUMMARY:-}" ]; then
    printf 'Published [%s](https://github.com/%s/releases/tag/%s) and updated **MicroCol Dev**.\n' "$BUILD" "$REPOSITORY" "$BUILD" >> "$GITHUB_STEP_SUMMARY"
fi
